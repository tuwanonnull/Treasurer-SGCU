import { chromium } from '@playwright/test';
import { readFile, mkdtemp } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
import { createPilotServer } from './server.mjs';

const source = await readFile(process.argv[2], 'utf8'), snapshot = JSON.parse(source);
const chosen = snapshot.projects.find(p => p.statuses.AZ !== 'ยกเลิกโครงการ'); assert.ok(chosen);
const directory = await mkdtemp(path.join(tmpdir(), 'sgcu-assistant-ui-')), trialDirectory = path.join(directory, 'store');
let server = createPilotServer({ year68Snapshot: snapshot, trialDirectory });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
let base = `http://127.0.0.1:${server.address().port}`, browser;
try {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } }), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const message = text => page.locator('#message').filter({ hasText: text }).waitFor();
  const role = async user => { await page.getByLabel('บัญชีทดลอง', { exact: true }).selectOption(user); await message('เปิดชุดทดลองแล้ว'); };
  const state = async () => (await page.request.get(base + '/api/year68/trial?q=' + encodeURIComponent(chosen.code))).json();
  const card = () => page.locator('#list details').first();
  const open = async () => { if (!await card().evaluate(el => el.open)) await card().locator('summary').click(); };
  const search = async () => { await page.getByLabel('ค้นหาโครงการ / องค์กร', { exact: true }).fill(chosen.code); await page.getByRole('button', { name: 'ค้นหา', exact: true }).click(); await message('โหลดผลค้นหาแล้ว'); };
  const assign = async value => { await open(); await card().getByLabel('ผู้ช่วยจำลอง', { exact: true }).selectOption(value); await card().getByLabel('เหตุผลมอบหมาย', { exact: true }).fill(''); await card().getByRole('button', { name: 'บันทึกผู้รับผิดชอบจำลอง', exact: true }).click(); await message('มอบหมายผู้ช่วยจำลองแล้ว'); };
  const change = async (field, value, review = false) => {
    await open(); await card().getByLabel('ช่องสถานะ', { exact: true }).selectOption(field);
    await card().getByLabel('สถานะใหม่', { exact: true }).selectOption(value);
    const reason = card().getByLabel('เหตุผลเปลี่ยนสถานะ', { exact: true });
    assert.equal(await reason.evaluate(el => el.required), review);
    await reason.fill(review ? 'ทดสอบขอยกเลิกโครงการ' : '');
    await card().getByRole('button', { name: 'ดูผลจากสถานะ', exact: true }).click(); await card().getByText('ผลสถานะและยอดก่อนบันทึก', { exact: true }).waitFor();
    await card().getByRole('button', { name: review ? 'เสนอเปลี่ยนสถานะให้เหรัญญิกตรวจ' : 'บันทึกสถานะในชุดทดลอง', exact: true }).click();
    await message(review ? 'เสนอเปลี่ยนสถานะแล้ว' : 'บันทึกสถานะและยอดที่เกี่ยวข้องแล้ว');
  };
  await page.goto(base + '/year68-trial'); await role('assistantA'); assert.equal((await state()).totalCount, 0);
  await role('head'); await search(); await assign('assistantA');
  await role('assistantA'); let current = await state(); assert.equal(current.totalCount, 1); assert.equal(current.projects[0].code, chosen.code);
  await open(); assert.equal(await card().getByLabel(snapshot.moneyLabels.O, { exact: true }).count(), 0); assert.equal(await card().getByLabel('ผู้ช่วยจำลอง', { exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'ล้างการทดลองและเริ่มจากสำเนาเดิม', exact: true }).isVisible(), false);
  await change('Q', chosen.statuses.Q === 'ผู้ช่วยตรวจสอบ' ? 'องค์กรกำลังดำเนินการ' : 'ผู้ช่วยตรวจสอบ');
  await role('assistantB'); assert.equal((await state()).totalCount, 0); assert.equal(await page.locator('#list details').count(), 0);
  await role('head'); await change('Q', 'เลขาตรวจสอบ');
  await role('assistantA'); await open();
  assert.equal(await card().getByLabel('ช่องสถานะ', { exact: true }).locator('option[value="Q"]').count(), 0);
  await card().getByText('สถานะโอนงบประมาณ: เลขาตรวจสอบ', { exact: true }).waitFor();
  await change('Y', chosen.statuses.Y === 'ผู้ช่วยตรวจสอบ' ? 'องค์กรกำลังดำเนินการ' : 'ผู้ช่วยตรวจสอบ');
  await change('AZ', 'ยกเลิกโครงการ', true); current = await state(); assert.equal(current.projects[0].statuses.AZ, chosen.statuses.AZ);
  await role('head'); await page.getByRole('button', { name: 'อนุมัติคำขอในชุดทดลอง', exact: true }).click(); await message('อนุมัติและคำนวณยอดที่เกี่ยวข้องแล้ว');
  assert.equal((await state()).projects[0].statuses.AZ, 'ยกเลิกโครงการ'); await assign('assistantB');
  await role('assistantA'); assert.equal((await state()).totalCount, 0);
  await role('assistantB'); const beforeRestart = await state(); assert.equal(beforeRestart.totalCount, 1);
  await new Promise(resolve => server.close(resolve)); server = createPilotServer({ year68Snapshot: snapshot, trialDirectory });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); base = `http://127.0.0.1:${server.address().port}`;
  await page.goto(base + '/year68-trial'); await role('assistantB'); current = await state(); assert.deepEqual(current.projects, beforeRestart.projects); assert.deepEqual(current.audit, beforeRestart.audit);
  await open(); assert.equal(await card().getByLabel('ช่องสถานะ', { exact: true }).count(), 0);
  assert.equal(await card().getByLabel('สถานะใหม่', { exact: true }).count(), 0);
  assert.equal(await card().getByLabel('เหตุผลเปลี่ยนสถานะ', { exact: true }).count(), 0);
  await card().getByText('ขณะนี้คุณไม่มีสถานะที่แก้ไขได้ในโครงการนี้', { exact: true }).waitFor();
  await card().getByText('สถานะโอนงบประมาณ: เลขาตรวจสอบ', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 }); assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await card().getByText('ขณะนี้คุณไม่มีสถานะที่แก้ไขได้ในโครงการนี้', { exact: true }).scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(directory, 'assistant-mobile.png') });
  assert.deepEqual(errors, []); assert.equal(await readFile(process.argv[2], 'utf8'), source);
  console.log(JSON.stringify({ result: 'PASS', checks: 'assignment, assistant visibility, no money controls, per-field lock, cancellation review, reassignment, restart, mobile, source unchanged', directory }));
} finally { if (browser) await browser.close(); await new Promise(resolve => server.close(resolve)); }
