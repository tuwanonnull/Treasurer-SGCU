import { chromium } from '@playwright/test';
import { readFile, mkdtemp } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
import { createPilotServer } from './server.mjs';
import { calculateMoney } from './finance.mjs';

const source = await readFile(process.argv[2], 'utf8'), snapshot = JSON.parse(source);
const chosen = snapshot.projects.find(p => p.money.O > 0 && p.statuses.H !== 'อนุมัติโครงการ' && !p.formulaInputs.hasLoanDocument);
assert.ok(chosen, 'Need a project eligible to demonstrate approval-status monetary effects');
const directory = await mkdtemp(path.join(tmpdir(), 'sgcu-status-ui-'));
const trialDirectory = path.join(directory, 'store');
let server = createPilotServer({ year68Snapshot: snapshot, trialDirectory });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
let base = `http://127.0.0.1:${server.address().port}`, browser;
try {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } }); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const message = text => page.locator('#message').filter({ hasText: text }).waitFor();
  const role = async user => { await page.getByLabel('บัญชีทดลอง', { exact: true }).selectOption(user); await message('เปิดชุดทดลองแล้ว'); };
  const search = async () => { await page.getByLabel('ค้นหาโครงการ / องค์กร', { exact: true }).fill(chosen.code); await page.getByRole('button', { name: 'ค้นหา', exact: true }).click(); await message('โหลดผลค้นหาแล้ว'); };
  const state = async () => (await page.request.get(base + '/api/year68/trial?q=' + encodeURIComponent(chosen.code))).json();
  const project = data => data.projects.find(p => p.sourceId === chosen.id);
  const change = async (field, value, button) => {
    const card = page.locator('#list details').first(); if (!await card.evaluate(el => el.open)) await card.locator('summary').click();
    await card.getByLabel('ช่องสถานะ', { exact: true }).selectOption(field);
    await card.getByLabel('สถานะใหม่', { exact: true }).selectOption(value);
    assert.equal(await card.getByLabel('เหตุผลเปลี่ยนสถานะ', { exact: true }).evaluate(el => el.required), false);
    await card.getByLabel('เหตุผลเปลี่ยนสถานะ', { exact: true }).fill('');
    assert.equal(await card.getByRole('button', { name: button, exact: true }).isDisabled(), true);
    await card.getByRole('button', { name: 'ดูผลจากสถานะ', exact: true }).click();
    await card.getByText('ผลสถานะและยอดก่อนบันทึก', { exact: true }).waitFor();
    await card.getByRole('button', { name: button, exact: true }).click();
  };
  await page.goto(base + '/year68-trial'); await role('secretary'); await search();
  await change('H', 'อนุมัติโครงการ', 'เสนอเปลี่ยนสถานะให้เหรัญญิกตรวจ'); await message('เสนอเปลี่ยนสถานะแล้ว');
  let data = await state(); assert.deepEqual(project(data).money, chosen.money); assert.deepEqual(project(data).statuses, chosen.statuses);
  await role('head'); await page.getByRole('button', { name: 'อนุมัติคำขอในชุดทดลอง', exact: true }).click(); await message('อนุมัติและคำนวณยอดที่เกี่ยวข้องแล้ว');
  data = await state(); assert.equal(project(data).statuses.H, 'อนุมัติโครงการ');
  assert.deepEqual(project(data).money, calculateMoney({ ...chosen, statuses: { ...chosen.statuses, H: 'อนุมัติโครงการ' } }));
  assert.notEqual(project(data).money.AE, chosen.money.AE);
  const transfer = project(data).statuses.Q === 'กระบวนการโอนงบประมาณมีผลบังคับใช้' ? 'องค์กรกำลังดำเนินการ' : 'กระบวนการโอนงบประมาณมีผลบังคับใช้';
  await change('Q', transfer, 'บันทึกสถานะในชุดทดลอง'); await message('บันทึกสถานะและยอดที่เกี่ยวข้องแล้ว');
  await role('secretary'); data = await state();
  const advance = project(data).statuses.Y === 'ส่งกิจการนิสิตแล้ว รออนุมัติ' ? 'องค์กรกำลังดำเนินการ' : 'ส่งกิจการนิสิตแล้ว รออนุมัติ';
  await change('Y', advance, 'บันทึกสถานะในชุดทดลอง'); await message('บันทึกสถานะและยอดที่เกี่ยวข้องแล้ว');
  data = await state(); assert.equal(project(data).statuses.Y, advance); assert.deepEqual(project(data).money, calculateMoney(project(data)));
  const beforeRestart = data;
  await new Promise(resolve => server.close(resolve)); server = createPilotServer({ year68Snapshot: snapshot, trialDirectory });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); base = `http://127.0.0.1:${server.address().port}`;
  await page.goto(base + '/year68-trial'); await role('secretary'); await search(); data = await state();
  assert.deepEqual(data.projects, beforeRestart.projects); assert.deepEqual(data.requests, beforeRestart.requests); assert.deepEqual(data.audit, beforeRestart.audit);
  await page.locator('#list summary').first().click();
  assert.equal(await page.getByLabel('ช่องสถานะ', { exact: true }).locator('option[value="AZ"], option[value="BA"]').count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByLabel('ช่องสถานะ', { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(directory, 'status-mobile.png') });
  const readonly = await (await page.request.get(base + '/api/year68')).json(); assert.deepEqual(readonly.totals, snapshot.totals);
  assert.equal(await readFile(process.argv[2], 'utf8'), source); assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'PASS', checks: 'status review, head approval with monetary effects, direct status by role, denied options, persistent restart, mobile, original unchanged', directory }));
} finally { if (browser) await browser.close(); await new Promise(resolve => server.close(resolve)); }
