import assert from 'node:assert/strict';
import { planAccessMigration } from '../migrations/unify-auth-access.mjs';
const str = stringValue => ({ stringValue });
const doc = (collection, fields) => ({ name: `projects/demo/databases/(default)/documents/${collection}/guest@example.com`, fields, updateTime: '2026-01-01T00:00:00Z' });
const legacy = doc('authAccessRequests', { email: str('guest@example.com'), uid: str('uid'), status: str('pending'), name: str('Name'), organization: str('Org'), reason: str('Work'), createdAt: { timestampValue: '2026-01-01T00:00:00Z' } });
const plan = planAccessMigration([], [legacy]);
assert.equal(plan.conflicts.length, 0); assert.equal(plan.writes.length, 2);
const merged = plan.writes[0].update;
assert.equal(merged.fields.active.booleanValue, false);
assert.equal(merged.fields.status.stringValue, 'pending');
assert.deepEqual(merged.fields.legacyApplication.mapValue.fields, legacy.fields);
assert.deepEqual(plan.writes[1].currentDocument, { updateTime: legacy.updateTime });
assert.equal(planAccessMigration([{ ...merged, updateTime: 'new' }], []).writes.length, 0);
const grant = doc('authEmailAccess', { email: str('guest@example.com'), active: { booleanValue: true }, startsAt: { timestampValue:'2026-01-01T00:00:00Z' }, endsAt: { timestampValue: '2030-01-01T00:00:00Z' } });
assert.equal(planAccessMigration([grant], [legacy]).conflicts.length, 1);
const approved = { ...legacy, fields: { ...legacy.fields, status: str('approved') } };
const combined = planAccessMigration([grant],[approved]);
assert.equal(combined.conflicts.length,0);
assert.deepEqual(combined.writes[0].update.fields.endsAt, grant.fields.endsAt);
assert.deepEqual(combined.writes[0].update.fields.active, grant.fields.active);
assert.deepEqual(combined.writes[0].currentDocument, { updateTime: grant.updateTime });
console.log('Migration plan: lossless application merge, existing grant preservation, stale-write preconditions, conflict rejection and idempotency passed.');
