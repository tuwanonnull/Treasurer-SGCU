import vm from 'node:vm';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const context = { window: {} };
vm.runInNewContext(await fs.readFile('web/js/features/budget/app.budget-meeting-roster.js', 'utf8'), context);
const build = context.window.sgcuBudgetMeetingRoster.organizations;
const catalog = [{ code: 'SGCU-01.00', name: 'A' }, { code: 'SGCU-01.02', name: 'Child' }, { code: 'SGCU-02.00', name: 'B' }];
const row = (id, code, role, year = '2569', status = 'approved') => ({ id, organizationCode: code, representativeRole: role, academicYear: year, status, requestType: 'organization_representative', applicantName: id, applicantEmail: `${id}@chula.ac.th` });
const rows = [row('chair', 'SGCU-01.00', 'ประธาน'), row('vice', 'SGCU-01.00', 'รองประธาน'), row('child', 'SGCU-01.02', 'ประธาน'), row('old', 'SGCU-01.00', 'ประธาน', '2568'), row('pending', 'SGCU-01.00', 'ประธาน', '2569', 'pending'), row('other', 'SGCU-02.00', 'กรรมการ')];
let result = build(catalog, rows, '2569');
assert.equal(result[0].members.length, 3);
assert.equal(result[0].members.find(m => m.id === 'chair@chula.ac.th').organizationName, 'A');
assert.equal(result[0].members.find(m => m.id === 'vice@chula.ac.th').organizationName, 'A');
assert.equal(result[0].members.find(m => m.id === 'child@chula.ac.th').organizationName, 'Child');
assert.equal(result[0].defaultRepresentative, 'chair@chula.ac.th');
assert.equal(result[1].members.length, 1);
assert.equal(result[1].defaultRepresentative, '');
assert.equal(build(catalog, [...rows, row('second', 'SGCU-01.00', 'ประธาน')], '2569')[0].defaultRepresentative, '');
const missing = row('missing', 'SGCU-02.00', 'ประธาน'); missing.applicantEmail = '';
assert.equal(build(catalog, [...rows, missing], '2569')[1].defaultRepresentative, '');
assert.equal(build(catalog, [...rows, rows[0]], '2569')[0].members.length, 3);
const legacyCatalog = [{ id: 'new', baseOrganizationId: 'base', code: 'SGCU-01.00', name: 'ฝ่ายหลัก', group: 'องค์การบริหารสโมสรนิสิต' }];
const legacy = { ...row('legacy', '', 'ดำรงตำแหน่งประธานฝ่าย'), organizationName: 'ฝ่ายหลัก', organizationType: 'องค์การบริหารสโมสรนิสิต', status: ' Approved ' };
assert.equal(build(legacyCatalog, [legacy], '2569')[0].defaultRepresentative, 'legacy@chula.ac.th');
assert.equal(build(legacyCatalog, [{ ...legacy, organizationName: '', baseOrganizationId: 'base' }], '2569')[0].defaultRepresentative, 'legacy@chula.ac.th');
assert.equal(build(legacyCatalog, [{ ...legacy, representativeRole: 'รองประธานฝ่าย' }], '2569')[0].defaultRepresentative, '');
assert.match(build(legacyCatalog, [{ ...legacy, representativeRole: 'รองประธานฝ่าย' }], '2569')[0].representativeIssue, /ไม่พบประธาน/);
console.log('Passed: year/status filtering, child members, parent president only, duplicate accounts, missing/ambiguous president.');
