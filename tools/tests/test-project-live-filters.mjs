import assert from 'node:assert/strict';
import {filterLiveProjects} from '../../functions/project-live/query-filters.mjs';
const projects=Array.from({length:60},(_,i)=>({id:i,year:2568,code:`P${i}`,name:`โครงการ ${i}`,organizationGroup:i%2?'ชมรม':'องค์การ',organization:i%2?'กีฬา':'กิจการนิสิต'}));
const before=JSON.stringify(projects);
const query=params=>filterLiveProjects(projects,new URLSearchParams(params));
assert.equal(query({group:'ชมรม'}).matched.length,30);
assert.equal(query({group:'ชมรม',organization:'กิจการนิสิต'}).matched.length,0);
assert.equal(query({group:'ชมรม',q:'P59'}).matched[0].id,59);
assert.equal(query({year:'2569'}).matched.length,0);
assert.equal(query({year:'all'}).matched.length,60);
assert.equal(query({group:'ชมรม',offset:'50'}).offset,25);
assert.equal(query({offset:'-1'}).offset,0);
assert.equal(query({q:'missing',offset:'25'}).offset,0);
assert.equal(query({q:'missing'}).filterOptions.organizations.length,2);
assert.equal(JSON.stringify(projects),before);
console.log('PASS: combined filters, all-page matching, dependent organization catalog, year scope, pagination bounds, immutable input');
