import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const source = await fs.readFile('web/js/core/app.visitor-stats.js', 'utf8');
const context = vm.createContext({ document: { addEventListener() {} } });
vm.runInContext(source, context);
const compare = context.compareVisitorPeriods;
const dates = Array.from({ length: 61 }, (_, i) => {
  const date = new Date('2026-01-01T00:00:00Z'); date.setUTCDate(date.getUTCDate() + i); return date.toISOString().slice(0, 10);
});
const data = Object.fromEntries(dates.map((key, i) => [key, i < 30 ? 10 : 20]));
data[dates.at(-1)] = 100000; // Today must never distort the comparison.
let result = compare(data, dates, 30);
assert.equal(result.percent, 100);
assert.equal(result.current, 600); assert.equal(result.previous, 300);
assert.equal(result.currentDates[0], dates[30]); assert.equal(result.previousDates.at(-1), dates[29]);
assert.equal(compare(data, dates, 7).percent, 0);
const decrease = Object.fromEntries(dates.map((key, i) => [key, i < 30 ? 20 : 10]));
assert.equal(compare(decrease, dates, 30).percent, -50);
const zeros = Object.fromEntries(dates.map(key => [key, 0]));
assert.equal(compare(zeros, dates, 30).percent, 0);
zeros[dates[40]] = 1;
assert.equal(compare(zeros, dates, 30).percent, null);
delete data[dates[10]];
assert.equal(compare(data, dates, 30).complete, false);
assert.equal(compare(data, dates, 30).percent, null);
assert.equal(compare({}, dates, 30).percent, null);
console.log('Visitor comparison: adjacent periods, year/month boundaries, excludes today, increases/decreases, zero baseline and missing history passed.');
const dateRange = context.visitorDateRange;
const group = context.visitorGroupDays;
assert.equal(dateRange('2024-02-28', '2024-03-01').length, 3);
assert.throws(() => dateRange('2026-02-30', '2026-03-01'));
assert.throws(() => dateRange('2026-03-01', '2026-02-28'));
assert.throws(() => dateRange('2020-01-01', '2026-01-01'));
const boundaryDays = dateRange('2026-01-30', '2026-02-03');
const boundaryValues = Object.fromEntries(boundaryDays.map(key => [key, 2]));
assert.deepEqual(Array.from(group(boundaryDays, boundaryValues, 'month'), x => x.value), [4, 6]);
assert.deepEqual(Array.from(group(boundaryDays, boundaryValues, 'week'), x => x.value), [6, 4]);
delete boundaryValues['2026-01-31'];
assert.equal(group(boundaryDays, boundaryValues, 'month')[0].value, null);
assert.equal(context.visitorCompare(boundaryValues, boundaryDays, []).percent, null);
console.log('Custom ranges: leap days, invalid/reversed/oversized ranges, calendar weeks/months and incomplete buckets passed.');
