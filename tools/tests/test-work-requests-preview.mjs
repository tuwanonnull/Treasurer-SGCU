import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '@playwright/test';
import { createWorkPreviewServer } from '../preview/serve-work-requests-preview.mjs';
const server = createWorkPreviewServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => {
    if (route.request().url().startsWith(origin + '/') || /^https:\/\/(fonts\.googleapis\.com|fonts\.gstatic\.com)\//.test(route.request().url())) return route.continue();
    external.push(route.request().url()); return route.abort();
  });
  await page.goto(origin);
  await page.locator('.request-row').first().waitFor();
  await page.evaluate(() => document.fonts.ready);
  assert.equal(await page.locator('.site-header .logo-title').innerText(), 'Treasurer SGCU');
  assert.equal(await page.locator('.site-footer').count(), 1);
  assert.equal(await page.locator('#work-panel .page-title').evaluate(el => getComputedStyle(el).fontSize), '20px', 'Real site CSS must be loaded');
  assert.equal(await page.locator('.request-row').count(), 6);
  assert.match(await page.locator('.request-row').first().innerText(), /BR-069-0128/);
  assert.equal(await page.locator('#count-action').innerText(), '2');
  assert.equal(await page.locator('.work-list .service-filters, .work-list .status-filters').count(), 0);
  await mkdir('.local/work-requests-preview', { recursive: true });
  await page.screenshot({ path: '.local/work-requests-preview/general-desktop.png', animations: 'disabled', fullPage: false });
  await page.locator('#service-filter').selectOption('borrow');
  assert.equal(await page.locator('.request-row').count(), 3);
  await page.locator('.page-switch [data-staff-mode="staff"]').click();
  assert.equal(await page.locator('[data-staff-mode-snapshot]').count(), 1, 'Uses the real website mode animation');
  await page.locator('[data-staff-mode-snapshot]').waitFor({ state: 'detached' });
  assert.equal(await page.locator('#staffModeToggle [data-staff-mode="staff"]').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#list-title').innerText(), 'งานที่ต้องจัดการ');
  assert.equal(await page.locator('.request-row').count(), 7);
  await page.screenshot({ path: '.local/work-requests-preview/staff-desktop.png', animations: 'disabled', fullPage: false });
  await page.locator('#service-filter').selectOption('meeting');
  assert.equal(await page.locator('.request-row').count(), 3);
  await page.locator('.page-switch [data-staff-mode="normal"]').click();
  assert.equal(await page.locator('#service-filter').inputValue(), 'borrow');
  assert.equal(await page.locator('.request-row').count(), 3);
  await page.locator('.page-switch [data-staff-mode="staff"]').click();
  assert.equal(await page.locator('#service-filter').inputValue(), 'meeting');
  await page.locator('#work-search').fill('<script>test</script>');
  assert.equal(await page.locator('#empty-state').isVisible(), true);
  await page.locator('#clear-filters').click();
  assert.equal(await page.locator('.request-row').count(), 7);
  await page.locator('.summary-card[data-bucket="action"]').click();
  assert.equal(await page.locator('.request-row').count(), 5);
  await page.locator('.request-row[data-detail="BG-069-0036"]').click();
  assert.equal(await page.locator('#request-dialog').isVisible(), true);
  await page.locator('#demo-action').click();
  assert.equal(await page.locator('#request-dialog').isVisible(), false);
  assert.equal(await page.locator('#count-action').innerText(), '4');
  assert.equal(await page.locator('#staff-count').innerText(), '4');
  await page.locator('#reset-demo').click();
  assert.equal(await page.locator('#count-action').innerText(), '5');
  await page.locator('#desktopNavStaff .nav-group-toggle').filter({ hasText: 'บัญชีของฉัน' }).click();
  await page.locator('#desktopNavStaff a[data-page="login"]').click();
  assert.equal(await page.locator('#profile-panel').isVisible(), true);
  assert.equal(await page.locator('#staffModeToggle [data-staff-mode="staff"]').getAttribute('aria-pressed'), 'true');
  await page.locator('#staffModeToggle [data-staff-mode="normal"]').click();
  assert.equal(await page.locator('#desktopNavGeneral').isVisible(), true);
  assert.equal(await page.locator('#profile-panel button').filter({ hasText: /^งานและคำขอ$/ }).count(), 0);
  await page.locator('#desktopNavGeneral .nav-group-toggle').filter({ hasText: 'บัญชีของฉัน' }).click();
  await page.locator('#desktopNavGeneral a[data-page="account-work"]').click();
  assert.equal(await page.locator('#list-title').innerText(), 'คำขอของฉัน');
  await page.locator('#demo-role').selectOption('meeting');
  await page.locator('.page-switch [data-staff-mode="staff"]').click();
  assert.equal(await page.locator('.request-row').count(), 3);
  assert.equal(await page.locator('#service-filter option[value="budget"]').isDisabled(), true);
  assert.equal(await page.locator('#staff-count').innerText(), '2');
  for (const text of await page.locator('.request-row').allInnerTexts()) assert.match(text, /MT-069/);
  await page.locator('#demo-role').selectOption('user');
  assert.equal(await page.locator('.page-switch').isVisible(), false);
  assert.equal(await page.locator('#staffModeToggle').isVisible(), false);
  assert.equal(await page.locator('#list-title').innerText(), 'คำขอของฉัน');
  await page.locator('#demo-role').selectOption('staff');
  for (const width of [768, 390, 360]) {
    await page.setViewportSize({ width, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No horizontal overflow at ${width}px`);
  }
  await page.setViewportSize({ width: 390, height: 900 });
  await page.locator('#hamburgerBtn').click();
  assert.equal(await page.locator('#mobileMenu').getAttribute('aria-hidden'), 'false');
  await page.locator('#mobileMenu summary').filter({ hasText: /^บัญชี$/ }).click();
  await page.locator('#mobileMenu a[data-page="login"]').click();
  assert.equal(await page.locator('#profile-panel').isVisible(), true);
  await page.locator('#hamburgerBtn').click();
  await page.locator('#mobileMenu a[data-page="account-work"]').click();
  await page.screenshot({ path: '.local/work-requests-preview/general-mobile.png', animations: 'disabled', fullPage: true });
  await page.locator('.page-switch [data-staff-mode="staff"]').click();
  await page.screenshot({ path: '.local/work-requests-preview/staff-mobile.png', animations: 'disabled', fullPage: true });
  await page.locator('.request-row[data-detail="MT-069-0089"]').click();
  await page.screenshot({ path: '.local/work-requests-preview/detail-mobile.png', animations: 'disabled', fullPage: true });
  await page.keyboard.press('Escape');
  await page.locator('#request-dialog').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('#request-dialog').isVisible(), false);
  await page.locator('#demo-theme').selectOption('dark');
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  await page.screenshot({ path: '.local/work-requests-preview/staff-mobile-dark.png', animations: 'disabled', fullPage: true });
  assert.deepEqual(errors, []);
  assert.deepEqual(external, [], 'Preview may load the real Google font, but must not contact production services');
  assert.equal((await fetch(`${origin}/firestore.rules`)).status, 404);
  assert.equal((await fetch(`${origin}/preview.js`, { method: 'POST' })).status, 404);
  console.log('Work preview: synchronized modes, per-mode filters, role scopes, search/empty state, details, demo actions, reset, responsive layouts and no external requests passed.');
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
}
